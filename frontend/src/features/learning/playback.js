// Сколько видео действительно проиграли — считает эта функция, а не позиция ползунка.
//
// Позиция прыгает куда угодно: перемотка вперёд, назад, повтор куска. Если считать по ней,
// перетаскивание в конец засчитает лекцию, которую никто не смотрел. Поэтому время
// набирается только маленькими шагами, какие бывают при обычном проигрывании; всё, что
// больше, — это перемотка, и она не считается ничем.

// Событие timeupdate приходит примерно четыре раза в секунду, но вкладка в фоне и слабая
// машина растягивают промежуток. Два секунды — потолок «обычного шага».
const MAX_STEP_SECONDS = 2
// Как часто отправлять накопленное. Реже — дешевле для сервера, но при закрытии вкладки
// теряется больше: пятнадцать секунд — цена, которую видно только в редком случае.
const REPORT_EVERY_SECONDS = 15

/**
 * Счётчик проигранного времени для одного плеера.
 *
 * Возвращает объект с двумя действиями: сообщить о новой позиции и забрать накопленное.
 * Ничего не отправляет сам — отправкой занимается страница, а здесь только арифметика,
 * которую можно проверить без браузера.
 */
export function createPlaybackTracker({ reportEvery = REPORT_EVERY_SECONDS } = {}) {
  let previousTime = null
  let pending = 0

  return {
    /**
     * Учесть новую позицию плеера.
     *
     * Возвращает накопленные секунды, когда их накопилось достаточно для отправки, и ноль
     * во всех остальных случаях, включая перемотку.
     */
    advance(currentTime) {
      const step = previousTime === null ? 0 : currentTime - previousTime
      previousTime = currentTime
      // Шаг назад — это перемотка назад, шаг больше двух секунд — перемотка вперёд или
      // пропуск кадров. Ни то, ни другое человек не смотрел.
      if (step > 0 && step <= MAX_STEP_SECONDS) pending += step
      return pending >= reportEvery ? this.take() : 0
    },

    /** Забрать накопленное — при паузе, в конце и при уходе со страницы. */
    take() {
      const collected = Math.round(pending)
      pending -= collected
      return collected
    },

    /** Начать счёт заново: плеер перемотали или сменили лекцию. */
    reset() {
      previousTime = null
      pending = 0
    },
  }
}
